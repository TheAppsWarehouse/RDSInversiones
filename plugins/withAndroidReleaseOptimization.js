'use strict';

// Build-time Expo plugin. Uses Expo's existing config-plugin API; no runtime library added.
const { withGradleProperties, withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs/promises');
const path = require('node:path');

const releaseFlags = {
  // SDK 53's template uses Proguard naming even though the actual shrinker is R8.
  'android.enableProguardInReleaseBuilds': 'true',
  // Current Expo templates use Minify naming. Retain compatibility with both templates.
  'android.enableMinifyInReleaseBuilds': 'true',
  'android.enableShrinkResourcesInReleaseBuilds': 'true',
};

function configureReleaseProperties(properties) {
  const preserved = properties.filter((entry) => entry.type !== 'property'
    || !Object.prototype.hasOwnProperty.call(releaseFlags, entry.key));
  return preserved.concat(Object.entries(releaseFlags).map(([key, value]) => ({
    type: 'property', key, value,
  })));
}

function configureReleaseGradle(contents) {
  let updated = contents.replace(
    /getDefaultProguardFile\(\s*(['"])proguard-android\.txt\1\s*\)/g,
    'getDefaultProguardFile("proguard-android-optimize.txt")',
  );
  if (!updated.includes('proguard-android-optimize.txt')) {
    throw new Error('[release-optimization] Expected the standard Expo Android Proguard configuration. Inspect the generated app/build.gradle before enabling this plugin on a custom template.');
  }
  let foundRulesLine = false;
  updated = updated.replace(/^([ \t]*proguardFiles[^\r\n]*getDefaultProguardFile[^\r\n]*)$/gm, (line) => {
    foundRulesLine = true;
    return line.includes('rds-release.pro') ? line : `${line}, "rds-release.pro"`;
  });
  if (!foundRulesLine) {
    throw new Error('[release-optimization] Expected a standard single-line Expo proguardFiles declaration. No native build configuration was silently guessed.');
  }
  return updated;
}

const releaseRules = `# RDS release-only rules, generated by the Expo config plugin.
# Keep dependency-provided consumer/JNI/reflection rules and normal R8 warnings.
# Do not add blanket -keep, -dontwarn, -dontoptimize, or forced control-flow obfuscation.
# Generic source filename with line numbers retained for private mapping.txt retracing.
-keepattributes SourceFile,LineNumberTable
-renamesourcefileattribute SourceFile
`;

function withAndroidReleaseOptimization(config) {
  config = withGradleProperties(config, (mod) => {
    mod.modResults = configureReleaseProperties(mod.modResults);
    return mod;
  });
  config = withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('[release-optimization] This plugin supports the Expo-generated Groovy Android template only.');
    }
    mod.modResults.contents = configureReleaseGradle(mod.modResults.contents);
    return mod;
  });
  return withDangerousMod(config, ['android', async (mod) => {
    // This is an owned generated rules file, not an overwrite of existing application rules.
    const appDirectory = path.join(mod.modRequest.platformProjectRoot, 'app');
    await fs.mkdir(appDirectory, { recursive: true });
    await fs.writeFile(path.join(appDirectory, 'rds-release.pro'), releaseRules, 'utf8');
    return mod;
  }]);
}

module.exports = withAndroidReleaseOptimization;
module.exports.configureReleaseProperties = configureReleaseProperties;
module.exports.configureReleaseGradle = configureReleaseGradle;
