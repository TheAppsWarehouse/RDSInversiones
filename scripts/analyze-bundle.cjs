#!/usr/bin/env node
'use strict';

// Local development utility, not an application dependency or a backend runtime.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { gzipSync } = require('node:zlib');

function collectFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    return entry.isDirectory() ? collectFiles(filename) : [filename];
  });
}

function analyzeBundle(platform) {
  if (!['android', 'ios', 'web'].includes(platform)) {
    throw new Error('Usage: node scripts/analyze-bundle.cjs [android|ios|web]');
  }
  const projectRoot = path.resolve(__dirname, '..');
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const outputDir = path.join(projectRoot, 'artifacts', 'bundle-analysis', `${platform}-${timestamp}`);
  // Use the installed Expo CLI through its package entry; no package.json modification.
  const expoPackage = require.resolve('expo/package.json', { paths: [projectRoot] });
  const expoManifest = JSON.parse(fs.readFileSync(expoPackage, 'utf8'));
  const cliEntry = typeof expoManifest.bin === 'string' ? expoManifest.bin : expoManifest.bin?.expo;
  if (!cliEntry) throw new Error('The installed Expo package has no CLI entry.');
  const cli = path.resolve(path.dirname(expoPackage), cliEntry);
  const result = spawnSync(process.execPath, [cli, 'export', '--platform', platform,
    '--source-maps', '--output-dir', outputDir], {
    cwd: projectRoot,
    env: { ...process.env, EXPO_ATLAS: 'true' },
    stdio: 'inherit',
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Expo export failed (${result.signal ?? result.status}). No size report generated.`);

  const allFiles = collectFiles(outputDir);
  const bundles = allFiles.filter((filename) => /\.(js|hbc|bundle)$/.test(filename));
  if (bundles.length === 0) throw new Error('No bundle files found in the Expo export. Inspect its output before reporting sizes.');
  const bundleFiles = bundles.map((filename) => {
    const contents = fs.readFileSync(filename);
    return {
      file: path.relative(outputDir, filename),
      bytes: contents.length,
      gzipBytes: gzipSync(contents).length,
    };
  });
  const mapBytes = allFiles.filter((filename) => filename.endsWith('.map'))
    .reduce((total, filename) => total + fs.statSync(filename).size, 0);
  const exportedBytes = allFiles.reduce((total, filename) => total + fs.statSync(filename).size, 0);
  const atlasSource = path.join(projectRoot, '.expo', 'atlas.jsonl');
  const atlasFile = path.join(outputDir, 'atlas.jsonl');
  if (fs.existsSync(atlasSource)) fs.copyFileSync(atlasSource, atlasFile);
  else console.warn('Expo Atlas output was not generated by this SDK; bundle sizes are still available.');

  const report = {
    platform,
    generatedAt: new Date().toISOString(),
    expoVersion: expoManifest.version,
    bundleFiles,
    bundleBytes: bundleFiles.reduce((total, file) => total + file.bytes, 0),
    bundleGzipBytes: bundleFiles.reduce((total, file) => total + file.gzipBytes, 0),
    exportedBytesExcludingSourceMaps: exportedBytes - mapBytes,
    sourceMapBytes: mapBytes,
    notes: [
      'Measured export files only; NOT APK/AAB/download size, DEX size, or runtime RAM.',
      'Gzip sizes are informational; native bytecode compression is not an install-size estimate.',
      'Atlas and source maps contain original source and inlined public environment values. Keep private.',
      'For dependency rankings, open the copied Atlas file with npx expo-atlas <path>.',
    ],
  };
  fs.writeFileSync(path.join(outputDir, 'bundle-size-report.json'), JSON.stringify(report, null, 2));
  console.table(bundleFiles);
  console.log(`Bundle bytes: ${report.bundleBytes}; informational gzip bytes: ${report.bundleGzipBytes}`);
  console.log(`Private report: ${outputDir}`);
  if (fs.existsSync(atlasFile)) console.log(`Inspect dependencies: npx expo-atlas "${atlasFile}"`);
  return report;
}

exports.analyzeBundle = analyzeBundle;
if (require.main === module) {
  try { analyzeBundle(process.argv[2] ?? 'android'); }
  catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
